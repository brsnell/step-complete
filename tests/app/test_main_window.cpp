QAction* menuAction(const MainWindow& window, const QString& menuTitle, const QString& text) {
  for (QAction* top : window.menuBar()->actions()) {
    if (top->menu() != nullptr && top->text() == menuTitle) {
      for (QAction* action : top->menu()->actions()) {
        if (action->text() == text) {
          return action;
        }
      }
    }
  }
  return nullptr;
}

