  // View > Saved Views (docs/designs/user-saved-views.md): a saved view brings back the camera,
  // the hidden parts and the section planes, and is still there when the file is opened again.
  void savedViewsRestoreCameraPartsAndSectionsAndPersist() {
    openFixture();
    auto* tree = _window->findChild<QTreeView*>(QStringLiteral("assemblyTreeView"));
    auto* viewport = _window->findChild<sc::render::OcctViewport*>();
    auto* section = _window->findChild<sc::render::SectionTool*>();
    QAction* hide = menuAction(*_window, QStringLiteral("&View"), QStringLiteral("&Hide"));
    QAction* showAll = menuAction(*_window, QStringLiteral("&View"), QStringLiteral("Show &All"));
    QVERIFY(tree && viewport && section && hide && showAll);
    // Looked up each time: closing the file rebuilds the tree, so an old index would dangle.
    const auto plateRow = [tree] {
      QAbstractItemModel* model = tree->model();
      const QModelIndex fixture = model->index(0, 0);
      for (int row = 0; row < model->rowCount(fixture); ++row) {
        if (model->index(row, 0, fixture).data().toString() == QStringLiteral("Base plate")) {
          return model->index(row, 0, fixture);
        }
      }
      return QModelIndex();
    };
    const auto plateShown = [&plateRow] {
      const QModelIndex plate = plateRow();
      return plate.isValid() && plate.data(Qt::CheckStateRole).toInt() == Qt::Checked;
    };
    QVERIFY(plateRow().isValid());

    // Hide the plate, cut along Y and look from the side in perspective.
    tree->selectionModel()->select(plateRow(),
                                   QItemSelectionModel::ClearAndSelect | QItemSelectionModel::Rows);
    hide->trigger();
    QVERIFY(!plateShown());
    sc::render::SectionPlane cut = section->plane(1);
    cut.enabled = true;
    cut.normal = gp_Dir(0, 1, 0);
    cut.offset = 12.5;
    section->setPlane(1, cut);
    viewport->setStandardView(V3d_Xpos);
    viewport->setPerspective(true);
    const sc::render::CameraState saved = viewport->cameraState();
    QVERIFY(_window->saveCurrentViewAs(QStringLiteral("  Side cut  ")));
    QCOMPARE(_window->userViews().size(), size_t(1));
    QCOMPARE(_window->userViews().front().name, QStringLiteral("Side cut"));

    // Change all three, then restore.
    showAll->trigger();
    section->reset();
    viewport->setPerspective(false);
    viewport->setStandardView(V3d_Zpos);
    QVERIFY(plateShown());
    _window->restoreUserView(0);
    QVERIFY(!plateShown());
    QVERIFY(section->plane(1).enabled);
    QVERIFY(section->plane(1).normal.IsEqual(gp_Dir(0, 1, 0), 1e-9));
    QCOMPARE(section->plane(1).offset, 12.5);
    QVERIFY(!section->plane(0).enabled);
    const sc::render::CameraState restored = viewport->cameraState();
    QVERIFY(restored.perspective);
    QVERIFY(restored.eye.IsEqual(saved.eye, 1e-6));
    QVERIFY(restored.center.IsEqual(saved.center, 1e-6));
    QVERIFY(restored.up.IsEqual(saved.up, 1e-9));
    QVERIFY(_window->statusBar()->currentMessage().contains(QStringLiteral("Side cut")));

    // The same name replaces the view rather than adding one.
    QVERIFY(_window->saveCurrentViewAs(QStringLiteral("side CUT")));
    QCOMPARE(_window->userViews().size(), size_t(1));

    // Close and open the file again: the view is still there and still works.
    _close->trigger();
    QVERIFY(_window->userViews().empty());
    openFixture();
    QCOMPARE(_window->userViews().size(), size_t(1));
    QVERIFY(plateRow().isValid());
    QVERIFY(plateShown());
    _window->restoreUserView(0);
    QVERIFY(!plateShown());
  }

  // Crash reports (docs/designs/crash-reporting.md): the context a report would contain follows
  // the app, including while a background job runs, and never names the file.
  // View > Exploded View (docs/designs/exploded-view.md): the parts move apart by the panel's
  // distance, the tools that work on the assembled model put them back, and they put it back.
  void explodedViewMovesPartsAndYieldsToOtherTools() {
    QAction* explode = menuAction(*_window, QStringLiteral("&View"), QStringLiteral("E&xploded View"));
    QAction* section = menuAction(*_window, QStringLiteral("&View"), QStringLiteral("Se&ction View"));
    QAction* distance = menuAction(*_window, QStringLiteral("&Measure"), QStringLiteral("&Distance"));
    QVERIFY(explode != nullptr);
    QVERIFY(section != nullptr);
    QVERIFY(distance != nullptr);
    QVERIFY(!explode->isEnabled()); // no model
    auto* viewport = _window->findChild<sc::render::OcctViewport*>();
    auto* dock = _window->findChild<QDockWidget*>(QStringLiteral("ExplodeDock"));
    QVERIFY(dock != nullptr);

    openFixture();
    QVERIFY(explode->isEnabled());
    // Where each displayed object is placed (the parts are connected instances).
    const auto placements = [viewport] {
      std::map<const AIS_InteractiveObject*, gp_XYZ> result;
      sc::occ::InteractiveList objects;
      viewport->context()->DisplayedObjects(objects);
      for (sc::occ::InteractiveList::Iterator it(objects); it.More(); it.Next()) {
        result[it.Value().get()] = it.Value()->LocalTransformation().TranslationPart();
      }
      return result;
    };
    const auto spread = [](const std::map<const AIS_InteractiveObject*, gp_XYZ>& from,
                           const std::map<const AIS_InteractiveObject*, gp_XYZ>& to) {
      double most = 0.0;
      for (const auto& [object, at] : from) {
        const auto it = to.find(object);
        if (it != to.end()) {
          most = std::max(most, (it->second - at).Modulus());
        }
      }
      return most;
    };
    const auto assembled = placements();
    _mass->trigger();
    QCOMPARE(_tool->witnessCount(), 1);

    explode->trigger();
    QVERIFY(_window->isExploded());
    QVERIFY(explode->isChecked());
    QVERIFY(dock->isVisible());
    QCOMPARE(_tool->witnessCount(), 0); // drawn on the assembled model: hidden
    QVERIFY(sc::app::crashContextText().contains(QStringLiteral("exploded view")));
    const double half = spread(assembled, placements());
    QVERIFY2(half > 1.0, qPrintable(QString::number(half)));
    _window->setExplodeDistance(100);
    const double full = spread(assembled, placements());
    QVERIFY2(std::abs(full - 2.0 * half) < 1e-6, qPrintable(QStringLiteral("%1 vs %2").arg(full).arg(half)));

    // Measuring collapses it; exploding stops measuring.
    distance->trigger();
    QVERIFY(_tool->isActive());
    QVERIFY(!_window->isExploded());
    QVERIFY(!explode->isChecked());
    QCOMPARE(_tool->witnessCount(), 1);
    QCOMPARE(spread(assembled, placements()), 0.0);
    explode->trigger();
    QVERIFY(_window->isExploded());
    QVERIFY(!_tool->isActive());

    // The section view and the exploded view exclude each other too.
    section->trigger();
    QVERIFY(section->isChecked());
    QVERIFY(!_window->isExploded());
    explode->trigger();
    QVERIFY(_window->isExploded());
    QVERIFY(!section->isChecked());

    // Moving the slider while collapsed explodes; Collapse and closing put the parts back.
    explode->trigger();
    QVERIFY(!_window->isExploded());
    _window->setExplodeDistance(30);
    QVERIFY(_window->isExploded());
    QCOMPARE(_window->explodeDistance(), 30);
    _close->trigger();
    QVERIFY(!_window->isExploded());
    QVERIFY(!explode->isEnabled());
  }

