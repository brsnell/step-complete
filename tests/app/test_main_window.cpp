  // A section plane's face pick and measuring never run together, and Esc cancels a pick.
  void sectionFacePickAndMeasuringExcludeEachOther() {
    openFixture();
    auto* section = _window->findChild<sc::render::SectionTool*>();
    QAction* distance = menuAction(*_window, QStringLiteral("&Measure"), QStringLiteral("&Distance"));
    QVERIFY(section != nullptr);
    QVERIFY(distance != nullptr);

    distance->trigger();
    QVERIFY(_tool->isActive());
    section->pickFace(0); // stops measuring first
    QVERIFY(section->isPicking());
    QVERIFY(!_tool->isActive());
    QVERIFY(_window->statusBar()->currentMessage().contains(QStringLiteral("plane 1")));

    distance->trigger(); // starting a measurement cancels the pick
    QVERIFY(_tool->isActive());
    QVERIFY(!section->isPicking());

    menuAction(*_window, QStringLiteral("&Measure"), QStringLiteral("&Stop Measuring"))->trigger();
    QVERIFY(!_tool->isActive());
    section->pickFace(1);
    QVERIFY(section->isPicking());
    QAction* cancel = nullptr;
    for (QAction* action : _window->actions()) {
      if (action->shortcut() == QKeySequence(Qt::Key_Escape) && action->isEnabled()) {
        QVERIFY2(cancel == nullptr, "two enabled Esc actions would be ambiguous");
        cancel = action;
      }
    }
    QVERIFY(cancel != nullptr); // Esc is live while a plane waits for a face
    auto* viewport = _window->findChild<sc::render::OcctViewport*>();
    _window->activateWindow();
    viewport->setFocus();
    QTRY_VERIFY(QApplication::focusWidget() == viewport);
    QTest::keyClick(viewport, Qt::Key_Escape);
    QTRY_VERIFY(!section->isPicking());
    QVERIFY(!cancel->isEnabled());
  }

  // View > Saved Views (docs/designs/user-saved-views.md): a saved view brings back the camera,
  // the hidden parts and the section planes, and is still there when the file is opened again.
  void savedViewsRestoreCameraPartsAndSectionsAndPersist() {
    openFixture();
    auto* tree = _window->findChild<QTreeView*>(QStringLiteral("assemblyTreeView"));
    auto* viewport = _window->findChild<sc::render::OcctViewport*>();
    auto* section = _window->findChild<sc::render::SectionTool*>();
    QAction* hide = menuAction(*_window, QStringLiteral("&View"), QStringLiteral("&Hide"));
    QAction* showAll = menuAction(*_window, QStringLiteral("&View"), QStringLiteral("Show &All"));
    QVERIFY(tree && viewport && section && hide && showAll);
    // Looked up each time: closing the file rebuilds the tree, so an old index would dangle.
    const auto plateRow = [tree] {
      QAbstractItemModel* model = tree->model();
      const QModelIndex fixture = model->index(0, 0);
      for (int row = 0; row < model->rowCount(fixture); ++row) {
        if (model->index(row, 0, fixture).data().toString() == QStringLiteral("Base plate")) {
          return model->index(row, 0, fixture);
        }
      }
      return QModelIndex();
    };
    const auto plateShown = [&plateRow] {
      const QModelIndex plate = plateRow();
      return plate.isValid() && plate.data(Qt::CheckStateRole).toInt() == Qt::Checked;
    };
    QVERIFY(plateRow().isValid());

    // Hide the plate, cut along Y and look from the side in perspective.
    tree->selectionModel()->select(plateRow(),
                                   QItemSelectionModel::ClearAndSelect | QItemSelectionModel::Rows);
    hide->trigger();
    QVERIFY(!plateShown());
    sc::render::SectionPlane cut = section->plane(1);
    cut.enabled = true;
    cut.normal = gp_Dir(0, 1, 0);
    cut.offset = 12.5;
    section->setPlane(1, cut);
    viewport->setStandardView(V3d_Xpos);
    viewport->setPerspective(true);
    const sc::render::CameraState saved = viewport->cameraState();
    QVERIFY(_window->saveCurrentViewAs(QStringLiteral("  Side cut  ")));
    QCOMPARE(_window->userViews().size(), size_t(1));
    QCOMPARE(_window->userViews().front().name, QStringLiteral("Side cut"));

    // Change all three, then restore.
    showAll->trigger();
    section->reset();
    viewport->setPerspective(false);
    viewport->setStandardView(V3d_Zpos);
    QVERIFY(plateShown());
    _window->restoreUserView(0);
    QVERIFY(!plateShown());
    QVERIFY(section->plane(1).enabled);
    QVERIFY(section->plane(1).normal.IsEqual(gp_Dir(0, 1, 0), 1e-9));
    QCOMPARE(section->plane(1).offset, 12.5);
    QVERIFY(!section->plane(0).enabled);
    const sc::render::CameraState restored = viewport->cameraState();
    QVERIFY(restored.perspective);
    QVERIFY(restored.eye.IsEqual(saved.eye, 1e-6));
    QVERIFY(restored.center.IsEqual(saved.center, 1e-6));
    QVERIFY(restored.up.IsEqual(saved.up, 1e-9));
    QVERIFY(_window->statusBar()->currentMessage().contains(QStringLiteral("Side cut")));

    // The same name replaces the view rather than adding one.
    QVERIFY(_window->saveCurrentViewAs(QStringLiteral("side CUT")));
    QCOMPARE(_window->userViews().size(), size_t(1));

    // Close and open the file again: the view is still there and still works.
    _close->trigger();
    QVERIFY(_window->userViews().empty());
    openFixture();
    QCOMPARE(_window->userViews().size(), size_t(1));
    QVERIFY(plateRow().isValid());
    QVERIFY(plateShown());
    _window->restoreUserView(0);
    QVERIFY(!plateShown());
  }

  // Measure > Set Material (docs/designs/material-density.md): mass properties of a part with a
  // material report its mass; parts without one say so; the material outlives a reopen.
  void materialsGiveMassAndPersist() {
    QDir(sc::app::ModelDataStore::defaultDirectory()).removeRecursively();
    openFixture();
    auto* tree = _window->findChild<QTreeView*>(QStringLiteral("assemblyTreeView"));
    auto* treeModel = _window->findChild<sc::app::AssemblyTreeModel*>();
    auto* proxy = qobject_cast<QSortFilterProxyModel*>(tree->model());
    QVERIFY(tree && treeModel && proxy);
    const auto plateRow = [tree] {
      QAbstractItemModel* model = tree->model();
      const QModelIndex fixture = model->index(0, 0);
      for (int row = 0; row < model->rowCount(fixture); ++row) {
        if (model->index(row, 0, fixture).data().toString() == QStringLiteral("Base plate")) {
          return model->index(row, 0, fixture);
        }
      }
      return QModelIndex();
    };
    const auto measurePlate = [&] {
      tree->selectionModel()->select(plateRow(),
                                     QItemSelectionModel::ClearAndSelect | QItemSelectionModel::Rows);
      _mass->trigger();
      return _panel->measurements().back();
    };
    const auto detail = [](const sc::core::Measurement& measurement, const std::string& key) {
      for (const auto& [k, v] : measurement.details) {
        if (k == key) {
          return v;
        }
      }
      return std::string("<missing>");
    };

    const sc::core::Measurement before = measurePlate();
    QVERIFY(before.ok);
    QCOMPARE(detail(before, "Mass"), std::string("no material set (Measure > Set Material)"));

    // Aluminium on the plate (100 x 60 x 10 mm = 60000 mm³): 0.162 kg.
    const sc::core::NodeId plate = treeModel->nodeId(proxy->mapToSource(plateRow()));
    QVERIFY(plate != sc::core::NoNode);
    _window->setMaterial({plate}, sc::core::Material{"Aluminium", 2700.0});
    QVERIFY(_window->materialOf(plate).has_value());
    QVERIFY(!_window->materialOf(plate)->fromFile);
    const sc::core::Measurement after = measurePlate();
    QCOMPARE(after.headline, std::string("0.162 kg"));
    QCOMPARE(detail(after, "Material"), std::string("Aluminium"));

    // Reopened: still aluminium. Cleared: back to no material.
    _close->trigger();
    openFixture();
    const sc::core::NodeId reopened = treeModel->nodeId(proxy->mapToSource(plateRow()));
    QVERIFY(_window->materialOf(reopened).has_value());
    QCOMPARE(measurePlate().headline, std::string("0.162 kg"));
    _window->setMaterial({reopened}, std::nullopt);
    QVERIFY(!_window->materialOf(reopened).has_value());
    QCOMPARE(detail(measurePlate(), "Mass"), std::string("no material set (Measure > Set Material)"));
  }

  // File > Export Parts List (docs/designs/parts-list-export.md): the fixture's bill of materials,
  // and only the visible parts when asked.
  void exportPartsListWritesOneRowPerPart() {
    openFixture();
    QAction* exportList =
        menuAction(*_window, QStringLiteral("&File"), QStringLiteral("Export &Parts List..."));
    QVERIFY(exportList != nullptr);
    QVERIFY(exportList->isEnabled());
    const auto readLines = [](const QString& path) {
      QFile file(path);
      if (!file.open(QIODevice::ReadOnly)) {
        return QStringList();
      }
      QByteArray bytes = file.readAll();
      if (!bytes.startsWith("\xEF\xBB\xBF")) {
        return QStringList(QStringLiteral("<no BOM>"));
      }
      return QString::fromUtf8(bytes.mid(3)).split(QLatin1Char('\n'), Qt::SkipEmptyParts);
    };

    const QString all = QString::fromStdString(sc::test::tempPath("parts_all.csv"));
    QVERIFY(_window->exportPartsListTo(all, sc::core::PartsListOptions(), false));
    const QStringList rows = readLines(all);
    QCOMPARE(rows.size(), 4); // header, plate, pin, total
    QVERIFY2(rows[0].startsWith(QStringLiteral("Item,Quantity,Part,Instance names,Used in,")),
             qPrintable(rows[0]));
    QVERIFY2(rows[1].startsWith(QStringLiteral("1,1,Base plate,")), qPrintable(rows[1]));
    QVERIFY2(rows[2].startsWith(QStringLiteral("2,4,Pin ")), qPrintable(rows[2]));
    QVERIFY2(rows[3].startsWith(QStringLiteral("Total,5,")), qPrintable(rows[3]));
    QVERIFY(_window->statusBar()->currentMessage().contains(QStringLiteral("2 part")));

    // Hide the plate: the visible-only list has the pins alone.
    auto* tree = _window->findChild<QTreeView*>(QStringLiteral("assemblyTreeView"));
    QAbstractItemModel* model = tree->model();
    const QModelIndex fixture = model->index(0, 0);
    for (int row = 0; row < model->rowCount(fixture); ++row) {
      const QModelIndex child = model->index(row, 0, fixture);
      if (child.data().toString() == QStringLiteral("Base plate")) {
        tree->selectionModel()->select(child,
                                       QItemSelectionModel::ClearAndSelect | QItemSelectionModel::Rows);
      }
    }
    menuAction(*_window, QStringLiteral("&View"), QStringLiteral("&Hide"))->trigger();
    const QString visible = QString::fromStdString(sc::test::tempPath("parts_visible.csv"));
    QVERIFY(_window->exportPartsListTo(visible, sc::core::PartsListOptions(), true));
    const QStringList visibleRows = readLines(visible);
    QCOMPARE(visibleRows.size(), 3);
    QVERIFY2(visibleRows[1].startsWith(QStringLiteral("1,4,Pin ")), qPrintable(visibleRows[1]));
  }

